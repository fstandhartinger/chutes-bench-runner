def _load_jsonl_from_path(path: str) -> list[dict[str, Any]]:
    """Load a JSONL file from disk."""
    items = []
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                items.append(json.loads(line))
    return items


def _extract_json_from_response(text: str) -> Optional[dict[str, Any]]:
    """Extract JSON object from LLM response, handling markdown fences and thinking tags."""
    if not text:
        return None

    # Strip thinking tags
    cleaned = re.sub(r"(?i)<think>.*?</think>", "", text, flags=re.DOTALL).strip()
    if not cleaned:
        return None

    # Method 1: Try direct parse if it looks like JSON
    stripped = cleaned.strip()
    if stripped.startswith("{") and stripped.endswith("}"):
        try:
            return json.loads(stripped)
        except json.JSONDecodeError:
            pass

    # Method 2: Extract from ```json ... ``` fences
    match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", cleaned)
    if match:
        try:
            return json.loads(match.group(1).strip())
        except json.JSONDecodeError:
            pass

    # Method 3: Find outermost curly braces
    brace_start = cleaned.find("{")
    brace_end = cleaned.rfind("}")
    if brace_start != -1 and brace_end > brace_start:
        try:
            return json.loads(cleaned[brace_start : brace_end + 1])
        except json.JSONDecodeError:
            pass

    return None


def _calculate_weighted_scores(
    llm_output: dict[str, Any],
    dimension_weights: dict[str, float],
    criteria_weights: dict[str, dict[str, float]],
) -> dict[str, Any]:
    """Calculate weighted RACE scores from LLM judge output.

    Follows the same logic as utils/score_calculator.py from the original repo.

    Returns a dict with:
      target_total, reference_total, normalized_overall,
      per-dimension target/reference/normalized scores.
    """
    target_total = 0.0
    reference_total = 0.0
    dim_scores: dict[str, dict[str, float]] = {}

    for dim in EXPECTED_DIMENSIONS:
        scores_list = llm_output.get(dim)
        if not isinstance(scores_list, list):
            continue

        dim_weight = dimension_weights.get(dim, 0.0)
        crit_map = criteria_weights.get(dim, {})
        if not crit_map:
            continue

        dim_target_weighted = 0.0
        dim_ref_weighted = 0.0
        dim_total_weight = 0.0

        for item in scores_list:
            if not isinstance(item, dict):
                continue
            criterion_text = (item.get("criterion") or "").strip()
            a1_raw = item.get("article_1_score")
            a2_raw = item.get("article_2_score")
            try:
                a1 = float(a1_raw) if a1_raw is not None else None
                a2 = float(a2_raw) if a2_raw is not None else None
            except (ValueError, TypeError):
                continue

            if a1 is None:
                continue

            # Match criterion to weight (exact -> case-insensitive -> substring)
            weight = crit_map.get(criterion_text)
            if weight is None:
                lower = criterion_text.lower()
                for k, v in crit_map.items():
                    if k.lower() == lower:
                        weight = v
                        break
            if weight is None:
                lower = criterion_text.lower()
                for k, v in crit_map.items():
                    if lower in k.lower() or k.lower() in lower:
                        weight = v
                        break
            if weight is None:
                # Fallback to average weight for this dimension
                weight = sum(crit_map.values()) / len(crit_map)

            dim_target_weighted += a1 * weight
            dim_total_weight += weight
            if a2 is not None:
                dim_ref_weighted += a2 * weight

        if dim_total_weight > 0:
            dim_target_avg = dim_target_weighted / dim_total_weight
            dim_ref_avg = dim_ref_weighted / dim_total_weight
        else:
            dim_target_avg = 0.0
            dim_ref_avg = 0.0

        target_total += dim_target_avg * dim_weight
        reference_total += dim_ref_avg * dim_weight

        # Per-dimension normalized score
        denom = dim_target_avg + dim_ref_avg
        dim_norm = dim_target_avg / denom if denom > 0 else 0.0
        dim_scores[dim] = {
            "target": dim_target_avg,
            "reference": dim_ref_avg,
            "normalized": dim_norm,
        }

    overall_denom = target_total + reference_total
    normalized_overall = target_total / overall_denom if overall_denom > 0 else 0.0

    return {
        "target_total": target_total,
        "reference_total": reference_total,
        "normalized_overall": normalized_overall,
        "dimensions": dim_scores,
    }


