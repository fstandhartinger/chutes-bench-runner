@register_adapter("deepresearch_bench")
class DeepResearchBenchAdapter(BenchmarkAdapter):
    """DeepResearch-Bench (RACE) for evaluating deep research API quality.

    This adapter:
      1. Sends each English query to the chutes search API to obtain a
         research report (the "target" article).
      2. Uses the bench-runner's model under test as an LLM judge to
         compare the target article against a reference article using
         the RACE static scoring prompt.
      3. Computes a normalized RACE score:
         ``target_total / (target_total + reference_total)``
         where 0.5 means parity with the reference.
    """

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._queries: list[dict[str, Any]] = []
        self._references: dict[int, dict[str, Any]] = {}  # keyed by id

        # Search API configuration (overridable via env)
        self._search_api_url = os.environ.get(
            "DEEPRESEARCH_SEARCH_API_URL",
            "https://search.chutes.ai/api/v1/research",
        )
        self._search_api_key = os.environ.get("CHUTES_API_KEY", "")
        self._search_mode = os.environ.get("DEEPRESEARCH_MODE", "light")
        self._search_optimization = os.environ.get(
            "DEEPRESEARCH_OPTIMIZATION_MODE", "balanced"
        )

    def _resolve_runtime_config(self) -> tuple[str, str, str]:
        """Resolve endpoint/mode/optimization with optional per-run overrides.

        A worker may attach `run_config` to the adapter (see worker runner).
        Supported run config structure:
        {
          "deepresearch": {
            "search_api_url": "https://.../api/v1/research",
            "mode": "light" | "max",
            "optimization_mode": "speed" | "balanced" | "quality"
          }
        }
        """
        search_api_url = self._search_api_url
        search_mode = self._search_mode
        search_optimization = self._search_optimization

        run_config = getattr(self, "run_config", None)
        if isinstance(run_config, dict):
            deep_cfg = run_config.get("deepresearch")
            if isinstance(deep_cfg, dict):
                cfg_url = deep_cfg.get("search_api_url")
                cfg_mode = deep_cfg.get("mode")
                cfg_opt = deep_cfg.get("optimization_mode")

                if isinstance(cfg_url, str) and cfg_url.strip():
                    search_api_url = cfg_url.strip()
                if isinstance(cfg_mode, str) and cfg_mode.strip():
                    search_mode = cfg_mode.strip()
                if isinstance(cfg_opt, str) and cfg_opt.strip():
                    search_optimization = cfg_opt.strip()

        return search_api_url, search_mode, search_optimization

    # -- Adapter metadata ----------------------------------------------------

    def get_name(self) -> str:
        return "deepresearch_bench"

    def get_display_name(self) -> str:
        return "DeepResearch-Bench (RACE)"

    def supports_parallel_items(self) -> bool:
        return True

    def get_item_concurrency(self) -> Optional[int]:
        """Limit concurrency to avoid overloading the search API."""
        return 3

    def get_item_timeout_seconds(self) -> Optional[int]:
        """Deep research can be slow; allow up to 6 minutes per item."""
        return 360

    # -- Data loading --------------------------------------------------------

    async def preload(self) -> None:
        if self._queries:
            return

        logger.info("DeepResearch-Bench: downloading dataset files")

        query_path = await download_http_file_async(
            QUERY_URL,
            cache_subdir="deepresearch_bench",
            filename="query.jsonl",
        )
        reference_path = await download_http_file_async(
            REFERENCE_URL,
            cache_subdir="deepresearch_bench",
            filename="reference.jsonl",
        )

        # Load and filter to English only
        all_queries = _load_jsonl_from_path(str(query_path))
        self._queries = [
            q for q in all_queries if q.get("language") == "en"
        ]

        all_refs = _load_jsonl_from_path(str(reference_path))
        # Build lookup by prompt text (matching strategy from original repo)
        # Also build by ID for direct lookup
        self._references_by_prompt: dict[str, dict[str, Any]] = {}
        self._references = {}
        for ref in all_refs:
            ref_id = ref.get("id")
            if ref_id is not None:
                self._references[int(ref_id)] = ref
            prompt_text = ref.get("prompt", "")
            if prompt_text:
                self._references_by_prompt[prompt_text] = ref

        logger.info(
            "DeepResearch-Bench: loaded %d English queries, %d references",
            len(self._queries),
            len(self._references),
        )

    async def get_total_items(self) -> int:
        if not self._queries:
            await self.preload()
        return len(self._queries)

    async def enumerate_items(self) -> AsyncIterator[str]:
        if not self._queries:
            await self.preload()
        for query in self._queries:
            yield str(query["id"])

    # -- Search API call -----------------------------------------------------

    async def _call_search_api(self, query_text: str) -> tuple[str, dict[str, Any]]:
        """Call search.chutes.ai and return (report_text, metadata)."""
        search_api_url, search_mode, search_optimization = self._resolve_runtime_config()
        headers = {
            "Authorization": f"Bearer {self._search_api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "query": query_text,
            "mode": search_mode,
            "optimizationMode": search_optimization,
            "stream": False,
        }

        timeout = httpx.Timeout(300.0, connect=30.0)
        async with httpx.AsyncClient(timeout=timeout) as http_client:
            response = await http_client.post(
                search_api_url,
                json=payload,
                headers=headers,
            )
            response.raise_for_status()
            data = response.json()

        message = data.get("message", "")
        sources = data.get("sources", [])
        meta = {
            "search_mode": search_mode,
            "search_optimization": search_optimization,
            "search_api_url": search_api_url,
            "sources_count": len(sources) if isinstance(sources, list) else 0,
            "response_length": len(message),
        }
        return message, meta

    # -- Evaluation ----------------------------------------------------------

    async def evaluate_item(self, item_id: str) -> ItemResult:
        if not self._queries:
            await self.preload()

        # Find the query
        query = next(
            (q for q in self._queries if str(q["id"]) == item_id), None
        )
        if not query:
            return ItemResult(item_id=item_id, error=f"Query {item_id} not found")

        query_id = int(query["id"])
        prompt_text = query.get("prompt", "")

        # Find reference article (try by prompt text first, then by ID)
        ref = self._references_by_prompt.get(prompt_text)
        if ref is None:
            ref = self._references.get(query_id)
        if not ref:
            return ItemResult(
                item_id=item_id,
                prompt=prompt_text,
                error=f"Reference article not found for query {item_id}",
            )

        reference_article = ref.get("article", "")
        if not reference_article:
            return ItemResult(
                item_id=item_id,
                prompt=prompt_text,
                error=f"Reference article is empty for query {item_id}",
            )

        # Step 1: Call search API to get the target article
        search_start = time.time()
        try:
            target_article, search_meta = await self._call_search_api(prompt_text)
        except Exception as exc:
            return ItemResult(
                item_id=item_id,
                prompt=prompt_text,
                error=f"Search API error: {exc}",
                metadata={"search_error": str(exc)},
            )
        search_latency_ms = int((time.time() - search_start) * 1000)

        if not target_article or not target_article.strip():
            return ItemResult(
                item_id=item_id,
                prompt=prompt_text,
                error="Search API returned empty report",
                latency_ms=search_latency_ms,
                metadata=search_meta,
            )

        # Step 2: Build the RACE judge prompt
        judge_prompt = RACE_STATIC_SCORE_PROMPT.format(
            task_prompt=prompt_text,
            article_1=target_article,
            article_2=reference_article,
        )

        # Step 3: Call the LLM judge (model under test in bench-runner)
        judge_start = time.time()
        judge_text: Optional[str] = None
        judge_meta: dict[str, Any] = {}
        max_judge_retries = 3

        for attempt in range(1, max_judge_retries + 1):
            try:
                judge_text, judge_meta = await self.client.get_completion_text(
                    self.model_slug,
                    judge_prompt,
                    temperature=0.0,
                    max_tokens=16384,
                    min_output_tokens=0,
                )
                if judge_text and judge_text.strip():
                    break
            except Exception as exc:
                logger.warning(
                    "DeepResearch-Bench: judge attempt %d/%d failed for item %s: %s",
                    attempt,
                    max_judge_retries,
                    item_id,
                    str(exc),
                )
                if attempt == max_judge_retries:
                    return ItemResult(
                        item_id=item_id,
                        prompt=prompt_text,
                        response=target_article[:2000],
                        error=f"Judge LLM error after {max_judge_retries} attempts: {exc}",
                        latency_ms=search_latency_ms,
                        metadata={**search_meta, "judge_error": str(exc)},
                    )

        judge_latency_ms = int((time.time() - judge_start) * 1000)
        total_latency_ms = search_latency_ms + judge_latency_ms

        if not judge_text or not judge_text.strip():
            return ItemResult(
                item_id=item_id,
                prompt=prompt_text,
                response=target_article[:2000],
                error="Judge LLM returned empty response",
                latency_ms=total_latency_ms,
                metadata={
                    **search_meta,
                    "judge_latency_ms": judge_latency_ms,
                    "search_latency_ms": search_latency_ms,
                },
            )

        # Step 4: Parse judge output
        llm_output = _extract_json_from_response(judge_text)
        if not llm_output:
            return ItemResult(
                item_id=item_id,
                prompt=prompt_text,
                response=target_article[:2000],
                error="Failed to parse JSON from judge response",
                latency_ms=total_latency_ms,
                judge_output={"raw_response": judge_text[:3000]},
                metadata={
                    **search_meta,
                    "judge_latency_ms": judge_latency_ms,
                    "search_latency_ms": search_latency_ms,
                },
            )

        # Validate expected dimensions
        missing_dims = [
            d for d in EXPECTED_DIMENSIONS if d not in llm_output
        ]
        if missing_dims:
            return ItemResult(
                item_id=item_id,
                prompt=prompt_text,
                response=target_article[:2000],
                error=f"Judge response missing dimensions: {missing_dims}",
                latency_ms=total_latency_ms,
                judge_output={
                    "raw_response": judge_text[:3000],
                    "parsed": llm_output,
                },
                metadata={
                    **search_meta,
                    "judge_latency_ms": judge_latency_ms,
                    "search_latency_ms": search_latency_ms,
                },
            )

        # Step 5: Calculate weighted scores
        criteria_weights: dict[str, dict[str, float]] = {}
        for dim, crit_list in STATIC_CRITERIA.items():
            criteria_weights[dim] = {c["criterion"]: c["weight"] for c in crit_list}

        try:
            scores = _calculate_weighted_scores(
                llm_output, STATIC_DIMENSION_WEIGHTS, criteria_weights
            )
        except Exception as exc:
            return ItemResult(
                item_id=item_id,
                prompt=prompt_text,
                response=target_article[:2000],
                error=f"Score calculation error: {exc}",
                latency_ms=total_latency_ms,
                judge_output={"parsed": llm_output},
                metadata={
                    **search_meta,
                    "judge_latency_ms": judge_latency_ms,
                    "search_latency_ms": search_latency_ms,
                },
            )

        normalized = scores["normalized_overall"]
        dim_scores = scores["dimensions"]

        # A score > 0.5 means the target outperforms the reference
        is_correct = normalized >= 0.5

        judge_output_payload = {
            "target_total": scores["target_total"],
            "reference_total": scores["reference_total"],
            "normalized_overall": normalized,
            "dimensions": dim_scores,
            "judge_model": self.model_slug,
            "judge_latency_ms": judge_latency_ms,
        }

        return ItemResult(
            item_id=item_id,
            item_hash=self.compute_item_hash(
                {"id": query_id, "prompt": prompt_text}
            ),
            prompt=prompt_text,
            response=target_article[:2000],
            expected=f"Reference article (id={ref.get('id')})",
            is_correct=is_correct,
            score=normalized,
            judge_output=judge_output_payload,
            latency_ms=total_latency_ms,
            input_tokens=judge_meta.get("prompt_tokens")
            or judge_meta.get("usage", {}).get("prompt_tokens"),
            output_tokens=judge_meta.get("completion_tokens")
            or judge_meta.get("usage", {}).get("completion_tokens"),
            metadata={
                "query_id": query_id,
                "topic": query.get("topic", ""),
                "search_latency_ms": search_latency_ms,
                "judge_latency_ms": judge_latency_ms,
                "target_total": scores["target_total"],
                "reference_total": scores["reference_total"],
                "normalized_overall": normalized,
                "comprehensiveness": dim_scores.get("comprehensiveness", {}).get(
                    "normalized", 0
                ),
                "insight": dim_scores.get("insight", {}).get("normalized", 0),
                "instruction_following": dim_scores.get(
                    "instruction_following", {}
                ).get("normalized", 0),
                "readability": dim_scores.get("readability", {}).get(
                    "normalized", 0
                ),
                **search_meta,
            },
        )

    # -- Postprocess ---------------------------------------------------------

    async def postprocess(self, results: list[ItemResult]) -> dict[str, Any]:
        """Compute per-dimension averages and overall RACE score."""
        successful = [r for r in results if r.score is not None and r.error is None]
        errors = [r for r in results if r.error is not None]

        if not successful:
            return {
                "race_score": 0.0,
                "errors": len(errors),
                "score_override": 0.0,
            }

        overall_scores = [r.score for r in successful]
        overall_avg = sum(overall_scores) / len(overall_scores)

        # Per-dimension averages
        dim_sums: dict[str, list[float]] = {d: [] for d in EXPECTED_DIMENSIONS}
        for r in successful:
            if r.metadata:
                for dim in EXPECTED_DIMENSIONS:
                    val = r.metadata.get(dim)
                    if val is not None:
                        dim_sums[dim].append(float(val))

        dim_avgs: dict[str, float] = {}
        for dim, vals in dim_sums.items():
            dim_avgs[f"{dim}_avg"] = sum(vals) / len(vals) if vals else 0.0

        # Canonical dimension keys for compatibility with the official output style.
        comprehensiveness = dim_avgs.get("comprehensiveness_avg", 0.0)
        insight = dim_avgs.get("insight_avg", 0.0)
        instruction_following = dim_avgs.get("instruction_following_avg", 0.0)
        readability = dim_avgs.get("readability_avg", 0.0)

        # Per-topic averages
        topic_scores: dict[str, list[float]] = {}
        for r in successful:
            topic = (r.metadata or {}).get("topic", "Unknown")
            topic_scores.setdefault(topic, []).append(r.score)
        topic_avgs = {
            topic: sum(vals) / len(vals) for topic, vals in topic_scores.items()
        }

        # Search latency stats
        search_latencies = [
            (r.metadata or {}).get("search_latency_ms", 0) for r in successful
        ]
        avg_search_latency = (
            sum(search_latencies) / len(search_latencies)
            if search_latencies
            else 0
        )

        return {
            "race_score": overall_avg,
            "overall_score": overall_avg,
            "score_override": overall_avg,
            **dim_avgs,
            "comprehensiveness": comprehensiveness,
            "insight": insight,
            "instruction_following": instruction_following,
            "readability": readability,
            "evaluation_summary": {
                "comprehensiveness": comprehensiveness,
                "insight": insight,
                "instruction_following": instruction_following,
                "readability": readability,
                "overall_score": overall_avg,
            },
            "completed": len(successful),
            "errors": len(errors),
            "topic_scores": topic_avgs,
            "avg_search_latency_ms": avg_search_latency,
        }
